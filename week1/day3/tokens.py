import os 
from pathlib import Path
from dotenv import load_dotenv
from groq import Groq

# ==============================================================================
# 1. ENVIRONMENT SETUP & CLIENT INITIALIZATION
# ==============================================================================
load_dotenv()

my_api_key = os.getenv("GROQ_API_KEY")

if not my_api_key:
    raise ValueError("API Error: GROQ_API_KEY not found in environment")

client = Groq(api_key=my_api_key)

# Active model on GroqCloud
model = "openai/gpt-oss-20b"


# ==============================================================================
# 2. WHAT IS A TOKEN & TOKEN UTILIZATION?
# ==============================================================================
# WHAT IS A TOKEN?
# • LLMs do not read words or letters directly. They process text in chunks called "tokens".
# • Rule of thumb in English:
#     1 token ≈ 4 characters or ~0.75 words.
#     100 tokens ≈ 75 words.
#
# WHAT IS TOKEN UTILIZATION?
# • Token utilization measures how many tokens your request consumed.
# • Every LLM API charges based on tokens (per 1K or 1M tokens).
# • In the API response, Groq returns a "usage" object with 3 key numbers:
#
#   1. prompt_tokens:
#      Tokens used by your input (including system prompt, user prompt, and chat history).
#
#   2. completion_tokens:
#      Tokens generated by the AI in its response.
#
#   3. total_tokens:
#      prompt_tokens + completion_tokens (the total cost/size of this API call).
# ==============================================================================


# ==============================================================================
# 3. ACTIVE CODE (Runs standard completion and prints token usage)
# ==============================================================================
role = "user"
prompt = "Do you know Padho with Pratyush"

message = {
    "role": role,
    "content": prompt
}

messages = [message]

response = client.chat.completions.create(
    model=model, 
    messages=messages
)

# Print the text response
print("################### AI RESPONSE ###################")
print(response.choices[0].message.content)

# Print Token Utilization Breakdown from response.usage
print("\n################# TOKEN UTILIZATION ################")
print(f"Input  Tokens (prompt_tokens):     {response.usage.prompt_tokens}")
print(f"Output Tokens (completion_tokens): {response.usage.completion_tokens}")
print(f"Total  Tokens (total_tokens):      {response.usage.total_tokens}")
print("###################################################")


